#[inline]
fn y_den(x: Fq2) -> Fq2 {
    let y = (x + Y_DEN_C0) * x;
    let z = (x + y + Y_DEN_C1) * (-x + y + Y_DEN_C2);
    let t = (x + y + z + Y_DEN_C3) * (-x - y + z + Y_DEN_C4);
    let u = (y + z + Y_DEN_C5) * (-y + z + Y_DEN_C6);
    let v = (x + Y_DEN_C7) * (y + Y_DEN_C8);
    let w = (x + Y_DEN_C9) * (y + Y_DEN_C10);
    let s = (x + z + t + v + Y_DEN_C11) * (x - z + t - v + Y_DEN_C12);
    let r = (z + u + Y_DEN_C13) * (-z + u + Y_DEN_C14);
    let q = (y + Y_DEN_C15) * (z + Y_DEN_C16);
    let p = (y + Y_DEN_C17) * (z + Y_DEN_C18);
    let o = (x + Y_DEN_C19) * (q + Y_DEN_C20);
    let m = (y + Y_DEN_C21) * (z + Y_DEN_C22);
    let j = (y + Y_DEN_C23) * (z + Y_DEN_C24);
    let h = (x + Y_DEN_C25) * (m + Y_DEN_C26);
    let g = (x + t + w + s + p + o + Y_DEN_C27) * (-x - t + w + s - p - o + Y_DEN_C28);
    let f = (x + t + r + Y_DEN_C29) * (-x - t + r + Y_DEN_C30);
    let e = (j + h + g + Y_DEN_C31) * x;
    f + e + Y_DEN_C32
}

/// The isogeny of `ISOGENY_MAP_TO_G2`, evaluated with 60 multiplications in
/// Fq2 (plus one for `y` and the batch inversion, as in the generic map).
pub(crate) fn isogeny_map_to_g2(point: Affine<SwuIsoConfig>) -> Affine<g2::Config> {
    match point.xy() {
        Some((x, y)) => {
            let mut v = [x_den(x), y_den(x)];
            batch_inversion(&mut v);
            Affine::new_unchecked(x_num(x) * v[0], y_num(x) * y * v[1])
        },
        None => Affine::identity(),
    }
}

#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn test_gen() {
        let gen: G2Affine = SwuIsoConfig::GENERATOR;
        assert!(gen.is_on_curve());
        assert!(gen.is_in_correct_subgroup_assuming_on_curve());
    }
    #[test]
    fn isogeny_chains_agree_with_horner() {
        use ark_ff::Field;
        use ark_std::{test_rng, vec::Vec, UniformRand};
        fn horner(coeffs: &[Fq2], x: &Fq2) -> Fq2 {
            coeffs.iter().rev().fold(Fq2::ZERO, |acc, c| acc * x + c)
        }
        let mut rng = test_rng();
        let map = &ISOGENY_MAP_TO_G2;
        let mut points: Vec<Fq2> = (0..1000).map(|_| Fq2::rand(&mut rng)).collect();
        points.extend([Fq2::ZERO, Fq2::ONE, -Fq2::ONE, SwuIsoConfig::GENERATOR.x]);
        for x in points {
            assert_eq!(x_num(x), horner(map.x_map_numerator, &x));
            assert_eq!(x_den(x), horner(map.x_map_denominator, &x));
            assert_eq!(y_num(x), horner(map.y_map_numerator, &x));
            assert_eq!(y_den(x), horner(map.y_map_denominator, &x));
        }
    }

    #[test]
    fn specialised_isogeny_map_agrees_with_generic() {
        use ark_std::{test_rng, UniformRand};
        let mut rng = test_rng();
        for _ in 0..100 {
            let p = G2Affine::rand(&mut rng);
            assert_eq!(isogeny_map_to_g2(p), ISOGENY_MAP_TO_G2.apply(p).unwrap());
        }
        assert_eq!(
            isogeny_map_to_g2(G2Affine::identity()),
            ISOGENY_MAP_TO_G2.apply(G2Affine::identity()).unwrap()
        );
    }
}
