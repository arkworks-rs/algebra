#[inline]
fn y_den(x: Fq) -> Fq {
    let y = (x + Y_DEN_C0) * x;
    let z = (x + y + Y_DEN_C1) * (-x + y + Y_DEN_C2);
    let t = (y + Y_DEN_C3) * (z + Y_DEN_C4);
    let u = (y + Y_DEN_C5) * (z + Y_DEN_C6);
    let v = (x + Y_DEN_C7) * (t + Y_DEN_C8);
    let w = (y + u + v + Y_DEN_C9) * (-y + u + v + Y_DEN_C10);
    let s = (y + z + Y_DEN_C11) * (-y + z + Y_DEN_C12);
    let r = (w + Y_DEN_C13) * x;
    w + s + r + Y_DEN_C14
}

/// The 11-isogeny of `ISOGENY_MAP_TO_G1`, evaluated with 30 multiplications
/// (plus one for `y` and the batch inversion, as in the generic map).
pub(crate) fn isogeny_map_to_g1(point: Affine<SwuIsoConfig>) -> Affine<g1::Config> {
    match point.xy() {
        Some((x, y)) => {
            let mut v = [x_den(x), y_den(x)];
            batch_inversion(&mut v);
            Affine::new_unchecked(x_num(x) * v[0], y_num(x) * y * v[1])
        },
        None => Affine::identity(),
    }
}

#[cfg(test)]
mod test {
    use super::*;

    use ark_ff::{AdditiveGroup, Field};
    use ark_std::{test_rng, vec::Vec, UniformRand};

    #[test]
    fn test_gen() {
        let gen: G1Affine = SwuIsoConfig::GENERATOR;
        assert!(gen.is_on_curve());
        assert!(gen.is_in_correct_subgroup_assuming_on_curve());
    }

    fn horner(coeffs: &[Fq], x: &Fq) -> Fq {
        coeffs.iter().rev().fold(Fq::ZERO, |acc, c| acc * x + c)
    }

    #[test]
    fn isogeny_chains_agree_with_horner() {
        let mut rng = test_rng();
        let map = &ISOGENY_MAP_TO_G1;
        let mut points: Vec<Fq> = (0..1000).map(|_| Fq::rand(&mut rng)).collect();
        points.extend([Fq::ZERO, Fq::ONE, -Fq::ONE, SwuIsoConfig::GENERATOR.x]);
        for x in points {
            assert_eq!(x_num(x), horner(map.x_map_numerator, &x));
            assert_eq!(x_den(x), horner(map.x_map_denominator, &x));
            assert_eq!(y_num(x), horner(map.y_map_numerator, &x));
            assert_eq!(y_den(x), horner(map.y_map_denominator, &x));
        }
    }

    #[test]
    fn specialised_isogeny_map_agrees_with_generic() {
        let mut rng = test_rng();
        for _ in 0..100 {
            let p = G1Affine::rand(&mut rng);
            assert_eq!(isogeny_map_to_g1(p), ISOGENY_MAP_TO_G1.apply(p).unwrap());
        }
        assert_eq!(
            isogeny_map_to_g1(G1Affine::identity()),
            ISOGENY_MAP_TO_G1.apply(G1Affine::identity()).unwrap()
        );
    }
}
